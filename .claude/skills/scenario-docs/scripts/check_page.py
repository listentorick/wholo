#!/usr/bin/env python3
"""Mechanical checks on a generated scenario page, the kind that break a Docusaurus build.

Usage:
    python3 check_page.py <docs_dir>/[<section>/]<id>.mdx
    python3 check_page.py --all <docs_dir>    every page, e.g. after moving pages between sections

Checks: front matter with title and description; the generated-file header; every
image reference (./img/<id>/<name>.png) points at a file that exists; no image in
img/<id>/ is left unreferenced; relative links to other pages resolve; admonitions
(:::note ... :::) are balanced. It can't judge the writing; read the page for that.
Exit code 1 if anything fails.
"""
import re
import sys
from pathlib import Path


def main(argv):
    if len(argv) == 3 and argv[1] == "--all":
        pages = sorted(Path(argv[2]).rglob("*.md*"))
        pages = [p for p in pages if p.suffix in (".md", ".mdx") and "node_modules" not in p.parts]
        return max([check(p, quiet_hand_written=True) for p in pages] or [0])
    if len(argv) != 2:
        print(__doc__)
        return 2
    return check(Path(argv[1]))


def check(page, quiet_hand_written=False):
    sid = page.stem
    text = page.read_text(encoding="utf-8")
    fails = []
    if quiet_hand_written and "Generated by scenario-docs" not in text:
        # A hand-written page (the home page): only its links can break the build.
        for target in re.findall(r"(?<!!)\]\((\.{1,2}/[^)#\s]+?\.mdx?)(?:#[^)]*)?\)", text):
            if not (page.parent / target).exists():
                print(f"FAIL  {page}: link to {target}, which doesn't exist.")
                fails.append(target)
        if not fails:
            print(f"OK   {page} (hand-written, links only)")
        return 1 if fails else 0

    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        fails.append("Front matter block missing at the top of the page.")
    else:
        fm = text[4:text.index("\n---\n", 4)]
        for key in ("title", "description"):
            if not re.search(rf"^{key}:\s*\S", fm, re.M):
                fails.append(f"Front matter has no {key}.")
    if "Generated by scenario-docs" not in text:
        fails.append("Generated-file header comment is missing.")

    refs = re.findall(r"!\[[^\]]*\]\((\./img/[^)\s]+)\)", text)
    img_dir = page.parent / "img" / sid
    referenced = set()
    for ref in refs:
        target = (page.parent / ref).resolve()
        if Path(ref).parent.name != sid:
            fails.append(f"{ref}: images should live in ./img/{sid}/.")
        if not target.exists():
            fails.append(f"{ref}: file doesn't exist.")
        referenced.add(target)
    for dup in sorted({r for r in refs if refs.count(r) > 1}):
        fails.append(f"{dup} is used more than once; each screenshot should appear once.")
    if img_dir.is_dir():
        for f in sorted(img_dir.iterdir()):
            if f.suffix.lower() in (".png", ".jpg", ".jpeg", ".webp", ".gif") \
                    and f.resolve() not in referenced:
                fails.append(f"{f} isn't used by the page (left over from an earlier run?).")

    for target in re.findall(r"(?<!!)\]\((\.{1,2}/[^)#\s]+?\.mdx?)(?:#[^)]*)?\)", text):
        if not (page.parent / target).exists():
            fails.append(f"Link to {target}, which doesn't exist (Docusaurus fails the build).")

    opens = len(re.findall(r"^:::[a-z]+", text, re.M))
    closes = len(re.findall(r"^:::\s*$", text, re.M))
    if opens != closes:
        fails.append(f"Admonitions unbalanced: {opens} opened, {closes} closed.")

    for f in fails:
        print(f"FAIL  {page}: {f}" if quiet_hand_written else f"FAIL  {f}")
    if not fails:
        print(f"OK   {page} ({len(refs)} screenshots)")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
